async function killAtReceipt(path: string, request: CommandRequest, point: "before" | "after") {
  const child = Bun.spawn([process.execPath, "--eval", `
    import { harness } from ${source("./support.ts")};
    import { Access } from ${source("../src/core/access.ts")};
    import { execute } from ${source("../src/core/commands.ts")};
    const { core, ledger } = harness(${JSON.stringify(path)});
    const request = ${JSON.stringify(request)};
    const die = () => process.kill(process.pid, "SIGKILL");
    if (${JSON.stringify(point)} === "before") ledger.putRequest = die;
    else ledger.subscribe(event => { if (event.data.type === "work") die(); });
    await execute(core, new Access({ kind: "owner" }), request, ${JSON.stringify(context)});
    throw new Error("fault point was not reached");
  `], { stdout: "pipe", stderr: "pipe" });
  const stderr = new Response(child.stderr).text();
  await child.exited;
  expect(await stderr).toBe("");
  expect(child.signalCode).toBe("SIGKILL");
}

function rejectReceipt(ledger: Ledger, requestId: string) {
  // UUIDs are generated by the test, never untrusted SQL input.
  ledger.db.exec(`CREATE TRIGGER reject_receipt BEFORE INSERT ON requests WHEN NEW.id = '${requestId}' BEGIN SELECT RAISE(ABORT, 'receipt fault'); END;`);
}

